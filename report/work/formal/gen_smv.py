"""
gen_smv.py -- generate the NuSMV models of the P17 DDD pacemaker controller.

The model is a register-level abstraction of rtl/ddd_pacemaker.v with the
millisecond timers scaled to abstract ticks (the orderings are what matter):

    AVI=2  VRP=3  PVARP=4  URI=5  LRI=10  ->  AEI = LRI-AVI = 8,  retrograde VA = 3

State variables  = the RTL registers (phase, t_v, t_av) + the heart / timebase
inputs (tick, a, v) as free variables. The per-tick decision (VS > VP > AS > AP)
is a set of DEFINEs written exactly like the RTL's blocking assignments, so a
NuSMV trace can be replayed on the RTL tick for tick.

Variants:
  ddd_oa.smv        over-approximating heart: a, v free every tick (all hearts)
  ddd_pmt.smv       AV block + retrograde VA conduction (PMT substrate)
  ddd_pmt_bug1.smv  BUG 1: PVARP blanking disabled  (PMT)
  ddd_oa_bug2.smv   BUG 2: VRP blanking removed     (V sense inside VRP)
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = """-- P17 DDD pacemaker controller (abstract ticks), generated by gen_smv.py
-- variant: {name}
MODULE main
DEFINE
  LRI := 10;  AVI_T := 2;  URI := 5;  PVARP := 4;  VRP := 3;  VA := 3;
  AEI := LRI - AVI_T;                 -- 8
  ENFORCE_PVARP := {pvarp};           -- FALSE = BUG 1
  CHECK_VRP     := {vrp};             -- FALSE = BUG 2
VAR
  phase : {{PH_AEI, PH_AVI}};          -- RTL register 'phase'
  t_v   : 0..11;                      -- RTL register 't_v'  (ticks since last V event, saturates at LRI+1)
  t_av  : 0..10;                      -- RTL register 't_av' (ticks since atrial event)
  tick  : boolean;                    -- 1 ms timebase strobe (free)
{heart_vars}
DEFINE
  -- RTL: tv = (t_v >= lri) ? lri+1 : t_v+1 ;  tav = (phase==AVI) ? t_av+1 : 0
  tv  := min(t_v + 1, LRI + 1);
  tav := (phase = PH_AVI) ? min(t_av + 1, 10) : 0;   -- RTL t_av never exceeds 4 (P0 below)
{heart_defs}
  -- event priority VS > VP > AS > AP (the event_priority block)
  VS := tick & v & (!CHECK_VRP | tv >= VRP);
  VP := tick & !VS & phase = PH_AVI & tav >= AVI_T & tv >= URI;
  blanked := ENFORCE_PVARP & tv < PVARP;
  AS := tick & !VS & !VP & phase = PH_AEI & a & !blanked;
  AP := tick & !VS & !VP & phase = PH_AEI & !AS & tv >= AEI;
  Vbeat := VS | VP;
  upper := Vbeat & tv <= URI;          -- RTL 'arrhythmia' (fast V-V interval)
  slow_vbeat := Vbeat & !upper;        -- a ventricular beat below the upper rate
ASSIGN
  init(phase) := PH_AEI;  init(t_v) := LRI;  init(t_av) := 0;   -- RTL reset values
  next(phase) := case !tick : phase;  VS | VP : PH_AEI;  AS | AP : PH_AVI;  TRUE : phase; esac;
  next(t_v)   := case !tick : t_v;    VS | VP : 0;       TRUE : tv; esac;
  next(t_av)  := case !tick : t_av;   VS | VP | AS | AP : 0;  TRUE : tav; esac;
{heart_assign}"""

OA_VARS = """  a     : boolean;                    -- intrinsic atrial event (free)
  v     : boolean;                    -- intrinsic ventricular event (free)"""
OA_DEFS = ""
OA_ASSIGN = ""

PMT_VARS = """  armed : boolean;                    -- retrograde conduction pending"""
PMT_DEFS = """  -- heart: complete AV block (no intrinsic V) + retrograde V->A conduction
  v := FALSE;
  a := tick & armed & tv = VA;        -- retrograde P wave VA ticks after a V event"""
PMT_ASSIGN = """  init(armed) := FALSE;
  next(armed) := case VS | VP : TRUE;  a : FALSE;  TRUE : armed; esac;"""

# --------------------------------------------------------------------------
# CTL properties (numbered as in the report table)
# --------------------------------------------------------------------------
OA_SPECS = [
    ("P0",  "Abstraction",  "AG t_av <= 4"),
    ("P1",  "Safety",       "AG !(AP & VP)"),
    ("P2",  "Safety",       "AG (VP -> tv >= URI)"),
    ("P3",  "Safety",       "AG (AS -> tv >= PVARP)"),
    ("P4",  "Safety",       "AG (VS -> tv >= VRP)"),
    ("P5",  "Safety",       "AG (VP -> tav >= AVI_T)"),
    ("P6",  "Safety",       "AG (AP -> tv >= AEI)"),
    ("P7",  "Reachability", "EF AP & EF VP & EF AS & EF VS"),
    ("P8",  "Non-blocking", "AG EF phase = PH_AEI"),
    ("P9",  "Liveness",     "AG AF Vbeat"),
    ("P10", "Until",        "AG ((AS | AP) -> AX A[ !(AS | AP) U Vbeat ])"),
]
PMT_SPECS = [
    ("P11", "PMT freedom",  "AG AF slow_vbeat"),
]


def model(name, env, pvarp=True, vrp=True, fair=False, specs=()):
    if env == "oa":
        hv, hd, ha = OA_VARS, OA_DEFS, OA_ASSIGN
    else:
        hv, hd, ha = PMT_VARS, PMT_DEFS, PMT_ASSIGN
    txt = HEADER.format(name=name, pvarp="TRUE" if pvarp else "FALSE",
                        vrp="TRUE" if vrp else "FALSE",
                        heart_vars=hv, heart_defs=hd, heart_assign=ha)
    if fair:
        txt += "FAIRNESS tick                       -- the 1 ms timebase never stops\n"
    for tag, kind, f in specs:
        txt += f"CTLSPEC NAME {tag} := {f};   -- {kind}\n"
    return txt


def main():
    files = {
        # same model, without and with the fairness constraint on the timebase
        "ddd_oa_nofair.smv":   model("oa, no fairness", "oa", specs=OA_SPECS),
        "ddd_oa.smv":          model("oa, FAIRNESS tick", "oa", fair=True, specs=OA_SPECS),
        "ddd_pmt.smv":         model("pmt, correct PVARP", "pmt", fair=True, specs=PMT_SPECS),
        "ddd_pmt_bug1.smv":    model("pmt, BUG1 PVARP disabled", "pmt", pvarp=False, fair=True,
                                     specs=PMT_SPECS),
        "ddd_oa_bug1.smv":     model("oa, BUG1 PVARP disabled", "oa", pvarp=False, fair=True,
                                     specs=OA_SPECS),
        "ddd_oa_bug2.smv":     model("oa, BUG2 VRP blanking removed", "oa", vrp=False, fair=True,
                                     specs=OA_SPECS),
    }
    for fn, txt in files.items():
        (HERE / fn).write_text(txt, encoding="ascii")
        print("wrote", fn)


if __name__ == "__main__":
    main()
