"""
gen_vectors.py -- inputs and golden outputs for the HW/SW cycle benchmark.

Takes the first NS samples of MIT-BIH record 100 (the same 11-bit codes the
board replays, rtl/tb_data/det_100_adc.txt), writes them as a C array for the
NEORV32 firmware, and computes the golden outputs with the project's bit-exact
models:
  * src/pan_tompkins_fixed.py::fixed_filter_chain  (== hls/qrs_stream.cpp)
  * src/qrs_hw_detector.py::detect_stream          (== rtl/qrs_decision.v)

Run:  ../../../.venv/Scripts/python gen_vectors.py [NS]
"""

import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "src"))

from pan_tompkins_fixed import fixed_filter_chain  # noqa: E402
from qrs_hw_detector import detect_stream          # noqa: E402

NS = int(sys.argv[1]) if len(sys.argv) > 1 else 2048
BASELINE = 1024

adc = np.loadtxt(os.path.join(ROOT, "rtl", "tb_data", "det_100_adc.txt"), dtype=np.int64)[:NS]
f = fixed_filter_chain(adc, BASELINE)
hp, dv, mwi = f["hp"], f["dv"], f["mwi"]
_, events = detect_stream(hp, dv, mwi)

os.makedirs(os.path.join(HERE, "fw"), exist_ok=True)
with open(os.path.join(HERE, "fw", "samples.h"), "w") as fh:
    fh.write("// generated by gen_vectors.py: first %d samples of MIT-BIH record 100 (11-bit ADC codes)\n" % NS)
    fh.write("#define NS %d\n" % NS)
    fh.write("static const int16_t ecg_samples[NS] = {\n")
    for i in range(0, NS, 16):
        fh.write("  " + ", ".join(str(int(v)) for v in adc[i:i + 16]) + ",\n")
    fh.write("};\n")

with open(os.path.join(HERE, "golden_filter.txt"), "w") as fh:
    for i in range(NS):
        fh.write("%d %d %d\n" % (hp[i], dv[i], mwi[i]))
with open(os.path.join(HERE, "golden_events.txt"), "w") as fh:
    for n, r, sb in events:
        fh.write("%d %d %d\n" % (n, r, int(sb)))

print("NS=%d samples, %d golden detections: %s" % (NS, len(events), events))
